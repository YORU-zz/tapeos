#!/usr/bin/env python3
"""Generate the embedded-build variant of the Tiny Scheme core
(build/scmcore-gen.inc) from src/tscore.inc.

The embedded core (SCMCORE, roadmap 61) is the same core source
as the standalone TSLOAD build, with three mechanical changes,
all applied to the generated copy only -- src/tscore.inc itself
is never modified, so TSLOAD stays byte-identical:

  1. The primitive tables (prim_name_ptrs / prim_table) lose
     the 18 primitives that belong to the standalone program's
     own interaction surface: console/keyboard I/O, the tape /
     script / menu machinery and the STAGE block editor.  In
     the embedded build those would fight the host program for
     the console and the tape; calling one of the names is a
     plain unbound-variable error (E_UNBOUND), the honest
     Scheme answer.  PRIM_COUNT drops 66 -> 48.
  2. Three loader-only data areas shrink to stubs (their only
     users are the removed primitives; the bodies stay in the
     file as dead code and still assemble): ftab (the tape
     file table), infobuf, linebuf.

usage: mkscmcore.py <src/tscore.inc> <build/scmcore-gen.inc>
"""
import re
import sys

EXCLUDED = {
    "display", "write", "newline", "readline", "readkey",
    "clear",
    "tapescan", "boot", "scripttext", "scriptsave",
    "scriptlen", "scriptsavecur", "exitmenu",
    "blockref", "blockset", "blocksplice", "blockfind",
    "blockls",
}

SHRINK = [
    ("ftab", r"12 \* 26", "2"),
    ("infobuf", r"36", "2"),
    ("linebuf", r"128", "2"),
]


def filter_table(lines, start_label, prefix):
    out = []
    kept, dropped = [], []
    i = 0
    while i < len(lines) and not lines[i].startswith(start_label + ":"):
        out.append(lines[i])
        i += 1
    assert i < len(lines), "table %s not found" % start_label
    out.append(lines[i])
    i += 1
    entries = []
    while i < len(lines):
        m = re.match(r"^\s*dw\s+(.*)$", lines[i])
        if not m:
            break
        items = [x.strip() for x in m.group(1).split(",")]
        if not all(re.match(r"^" + prefix + r"\w+$", x) for x in items):
            break
        entries.extend(items)
        i += 1
    assert len(entries) == 66, "%s: expected 66 entries, got %d" % (
        start_label, len(entries))
    for e in entries:
        suffix = e[len(prefix):]
        if suffix in EXCLUDED:
            dropped.append(e)
        else:
            kept.append(e)
    for j in range(0, len(kept), 5):
        out.append("        dw      " + ", ".join(kept[j:j + 5]))
    out.extend(lines[i:])
    return out, kept, dropped


def main():
    src = open(sys.argv[1]).read().splitlines()
    lines, kept_names, drop_names = filter_table(
        src, "prim_name_ptrs", "pn_")
    lines, kept_bodies, drop_bodies = filter_table(
        lines, "prim_table", "p_")
    assert [d[3:] for d in drop_names] == [d[2:] for d in drop_bodies], \
        "name/body exclusion mismatch"
    assert len(kept_names) == len(kept_bodies) == 48

    text = "\n".join(lines) + "\n"
    text, n = re.subn(r"^PRIM_COUNT\s+equ\s+66\s*$",
                      "PRIM_COUNT      equ     48", text,
                      flags=re.M)
    assert n == 1, "PRIM_COUNT not rewritten"
    for label, old, new in SHRINK:
        pat = r"^(%s:\s+ds\s+)%s\s*$" % (label, old)
        text, n = re.subn(pat, "\\g<1>" + new, text, flags=re.M)
        assert n == 1, "shrink for %s not applied" % label

    with open(sys.argv[2], "w") as f:
        f.write("; GENERATED by tools/mkscmcore.py from "
                "src/tscore.inc -- do not edit.\n")
        f.write("; Embedded build: 48 primitives (18 standalone-"
                "only removed), loader data areas shrunk.\n")
        f.write(text)
    print("mkscmcore: 66 -> %d primitives (%d excluded), "
          "PRIM_COUNT=48, data areas shrunk" % (
              len(kept_names), len(drop_names)))


if __name__ == "__main__":
    main()
