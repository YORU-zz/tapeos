#!/usr/bin/env python3
"""Generate build/stub.inc (db lines) from the stage-1
self-relocation stub template (tools/stub-template.bin,
109 bytes). The label `stubimg:` lives in src/tbc.z80;
this file carries only the data lines.

usage: genstub.py <stub-template.bin> <out.inc>
"""
import sys

tpl = open(sys.argv[1], "rb").read()
assert len(tpl) == 109, f"stub template is {len(tpl)} bytes"
with open(sys.argv[2], "w") as f:
    f.write("; generated by tools/genstub.py from "
            "tools/stub-template.bin\n")
    for i in range(0, len(tpl), 8):
        f.write("        db      " + ", ".join(
            "0%02xh" % b for b in tpl[i:i + 8]) + "\n")
print("stub.inc generated (109 bytes)")
