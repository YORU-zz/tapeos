#!/usr/bin/env python3
"""mklibtab.py -- build libtab.inc from tblib.z80.

Assembles the TinyBASIC library twice (ORG 0 and ORG 0x4000).
Bytes that differ between the two assemblies are the high
bytes of self-referential operands (an address inside the
same routine); words equal to 0xC000 + 3*id are calls to
another routine (dummy addresses). From those facts this
tool emits libtab.inc, which the compiler embeds:

  libtab:  20 entries x 16 bytes (all words):
             off, len, selfidx, nself, dumidx, ndum,
             dep_lo, dep_hi
           off/len locate the routine inside libimg;
           selfidx/dumidx are indices into libself/libdum;
           dep is the dependency bitmask (routine ids).
  libself: per entry: pos(2) tgt(2) -- operand position and
           target, both relative to the routine start.
  libdum:  per entry: pos(2) tgtid(1) pad(1).
  libimg:  the ORG 0 image bytes.

Usage: mklibtab.py <tblib.z80> <pasmo> <outdir>
Writes <outdir>/libtab.inc and <outdir>/libsym.txt.
"""
import re
import subprocess
import sys
from pathlib import Path

NROUT = 20


def assemble(pasmo, src_text, org, workdir, tag):
    src = workdir / f"tblib_{tag}.z80"
    src.write_text(src_text.replace("__ORG__", f"0{org:04x}h"))
    binp = workdir / f"tblib_{tag}.bin"
    symp = workdir / f"tblib_{tag}.sym"
    r = subprocess.run([pasmo, str(src), str(binp), str(symp)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout)
        print(r.stderr)
        raise SystemExit(f"pasmo failed for org {org:#x}")
    syms = {}
    for line in symp.read_text().splitlines():
        m = re.match(r"^(\S+)\s+EQU\s+([0-9A-Fa-f]+)H", line.strip())
        if m:
            syms[m.group(1)] = int(m.group(2), 16)
    return binp.read_bytes(), syms


def main():
    src_path, pasmo, outdir = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
    outdir.mkdir(parents=True, exist_ok=True)
    text = src_path.read_text()
    img0, sym0 = assemble(pasmo, text, 0x0000, outdir, "o0")
    img4, sym4 = assemble(pasmo, text, 0x4000, outdir, "o4")
    if len(img0) != len(img4):
        raise SystemExit("image length mismatch between origins")

    starts = [sym0[f"RTB_{i:02d}"] for i in range(NROUT)]
    end = sym0["RTB_END"]
    if starts[0] != 0:
        raise SystemExit("library does not start at 0")
    bounds = starts + [end]

    # --- self references from the two-origin diff ---
    selfrefs = []  # (routine, pos_in_routine, tgt_in_routine)
    diffpos = [i for i in range(len(img0)) if img0[i] != img4[i]]
    used = set()
    for p in diffpos:
        if img4[p] != (img0[p] + 0x40) & 0xFF:
            raise SystemExit(f"diff at {p:#x} is not a +0x4000 high byte")
        wpos = p - 1  # operand word starts one byte earlier
        val = img0[wpos] | (img0[wpos + 1] << 8)
        rid = max(i for i in range(NROUT) if bounds[i] <= wpos)
        if not (bounds[rid] <= val < bounds[rid + 1]):
            raise SystemExit(
                f"self-ref at {wpos:#x} (routine {rid}) targets "
                f"{val:#x}, outside the routine")
        if wpos in used:
            raise SystemExit(f"overlapping self-ref at {wpos:#x}")
        used.add(wpos)
        selfrefs.append((rid, wpos - bounds[rid], val - bounds[rid]))

    # --- dummy (cross-routine) references ---
    dumrefs = []  # (routine, pos_in_routine, target_id)
    for rid in range(NROUT):
        s, e = bounds[rid], bounds[rid + 1]
        for i in range(s, e - 1):
            v = img0[i] | (img0[i + 1] << 8)
            if 0xC000 <= v < 0xC000 + 3 * NROUT and (v - 0xC000) % 3 == 0:
                dumrefs.append((rid, i - s, (v - 0xC000) // 3))

    deps = [0] * NROUT
    for rid, _pos, tgt in dumrefs:
        deps[rid] |= 1 << tgt

    # --- emit libtab.inc ---
    lines = []
    lines.append("; generated by tools/mklibtab.py from tblib.z80 -- do not edit")
    lines.append(f"LIB_NROUT\tequ\t{NROUT}")
    lines.append(f"LIB_IMGSIZE\tequ\t{len(img0)}")
    lines.append("libtab:")
    self_by = {i: [r for r in selfrefs if r[0] == i] for i in range(NROUT)}
    dum_by = {i: [r for r in dumrefs if r[0] == i] for i in range(NROUT)}
    sidx = didx = 0
    for i in range(NROUT):
        lines.append(
            f"\tdw\t{bounds[i]},\t{bounds[i + 1] - bounds[i]},\t{sidx},"
            f"\t{len(self_by[i])},\t{didx},\t{len(dum_by[i])},"
            f"\t{deps[i] & 0xFFFF},\t{deps[i] >> 16}")
        sidx += len(self_by[i])
        didx += len(dum_by[i])
    lines.append("libself:")
    for rid in range(NROUT):
        for _r, pos, tgt in self_by[rid]:
            lines.append(f"\tdw\t{pos},\t{tgt}")
    lines.append("libdum:")
    for rid in range(NROUT):
        for _r, pos, tgt in dum_by[rid]:
            lines.append(f"\tdw\t{pos}\n\tdb\t{tgt},\t0")
    lines.append("libimg:")
    for i in range(0, len(img0), 16):
        chunk = ",\t".join(str(b) for b in img0[i:i + 16])
        lines.append(f"\tdb\t{chunk}")
    (outdir / "libtab.inc").write_text("\n".join(lines) + "\n")

    # --- human-readable summary ---
    names = ["rt_mul", "rt_div", "rt_mod", "rt_shl", "rt_shr",
             "x_prints", "x_printi", "x_printnl", "x_input",
             "x_locate", "x_cls", "x_inkey", "x_stick", "x_vsync",
             "x_peek", "x_poke", "x_putc", "neg_hl", "rtd_setup",
             "udiv_core"]
    rep = [f"tblib image: {len(img0)} bytes, {NROUT} routines"]
    for i in range(NROUT):
        rep.append(
            f"  {i:2d} {names[i]:9s} off {bounds[i]:4d} len "
            f"{bounds[i + 1] - bounds[i]:4d} self {len(self_by[i])} "
            f"dum {len(dum_by[i])} dep {deps[i]:#06x}")
    rep.append(f"selfrefs: {selfrefs}")
    rep.append(f"dumrefs:  {dumrefs}")
    (outdir / "libsym.txt").write_text("\n".join(rep) + "\n")
    print("\n".join(rep))


if __name__ == "__main__":
    main()
