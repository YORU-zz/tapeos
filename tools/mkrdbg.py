#!/usr/bin/env python3
"""mkrdbg.py - build the RDBG standalone debugger as a
TOSR (self-relocating) image.

The relocation bitmap is derived from a multi-ORG
assembly diff (the roadmap-50 technique, as in
reloc-stage1/tools/mktosr.py): the same source is
assembled at ORG 0x4000, 0x4100 and 0x4200. Every byte
that differs between the 0x4000 and 0x4100 builds must
differ by exactly +1 (a page delta), and the set of
differing positions must be identical between the
0x4000/0x4200 pair (delta +2). Those positions are the
high bytes of absolute operands; the bitmap marks
them (MSB-first, one bit per body byte). No mark is
declared by hand.

Outputs (in build/):
  rdbg.tosr       the deliverable image (origin 0x4000)
  rdbg0.tosr      negative control: same body, zero
                  bitmap (relocation disabled)
  rdbg_base.bin   the raw body at ORG 0x4000
  rdbg_base.sym   its symbol file
  rdbg-symbols.json  key addresses for the session
                  scripts and the checker

Host verification, done here before anything is
written out:
  - simulate() the stub's patch at deltas +0x58,
    +0x40 and -0x18 and compare byte-for-byte against
    FRESH assemblies at 0x9800 / 0x8000 / 0x2800 over
    the whole body (code and work areas alike).
  - the image checksum is recomputed the way the
    on-machine stub computes it (16-bit byte sum).
"""

import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
SRC = os.path.join(PROJ, "src")
BUILD = os.path.join(PROJ, "build")
PASMO = (os.environ.get("PASMO") or shutil.which("pasmo")
         or os.path.expanduser("~/workspace/tools/bin/pasmo"))

FORMAT_VERSION = 1
FLAG_STUB = 0x02
FLAG_ENTRY = 0x04

ORIGIN = 0x4000
ORGS = [0x4000, 0x4100, 0x4200]
FRESH = [0x9800, 0x8000, 0x2800]      # deltas +58/+40/-18


def parse_symbols(path):
    syms = {}
    for line in open(path):
        m = re.match(r"^(\S+)\s+EQU\s+([0-9A-F]+)H\s*$",
                     line.strip())
        if m:
            syms[m.group(1)] = int(m.group(2), 16)
    return syms


def write_def(org, body_size, total_size):
    with open(os.path.join(BUILD, "rdbgdef.inc"), "w") as f:
        f.write("; generated by mkrdbg.py - do not edit\n")
        f.write("ORGADDR         equ     0%04xh\n" % org)
        f.write("BODY_SIZE       equ     %d\n" % body_size)
        f.write("TOTAL_SIZE      equ     %d\n" % total_size)


def assemble(org, body_size, total_size, tag):
    write_def(org, body_size, total_size)
    binp = os.path.join(BUILD, "tmp_%s.bin" % tag)
    symp = os.path.join(BUILD, "tmp_%s.sym" % tag)
    r = subprocess.run([PASMO, "src/rdbg.z80", binp, symp],
                       cwd=PROJ, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        raise SystemExit("pasmo failed for ORG 0x%04x" % org)
    body = open(binp, "rb").read()
    syms = parse_symbols(symp)
    return body, syms


def build_image(body, bitmap, origin, entry_off):
    trailer = bytearray(16)
    trailer[0:2] = b"TR"
    trailer[2] = FORMAT_VERSION
    trailer[3] = FLAG_STUB | FLAG_ENTRY
    trailer[4] = (origin >> 8) & 0xFF
    trailer[5] = entry_off & 0xFF
    trailer[6] = (entry_off >> 8) & 0xFF
    trailer[7] = 0
    trailer[8] = len(body) & 0xFF
    trailer[9] = (len(body) >> 8) & 0xFF
    trailer[10] = len(bitmap) & 0xFF
    trailer[11] = (len(bitmap) >> 8) & 0xFF
    trailer[12] = 0
    trailer[13] = 0
    image = body + bitmap + bytes(trailer)
    cksum = sum(image) & 0xFFFF
    trailer[14] = cksum & 0xFF
    trailer[15] = (cksum >> 8) & 0xFF
    return body + bitmap + bytes(trailer)


def simulate(body, bitmap, delta):
    out = bytearray(body)
    for off in range(len(body)):
        if bitmap[off // 8] & (1 << (7 - (off % 8))):
            out[off] = (out[off] + delta) & 0xFF
    return bytes(out)


def main():
    os.makedirs(BUILD, exist_ok=True)
    # Pass 1: size discovery (BODY_SIZE feeds the stub's
    # constants; iterate until stable, mktosr pattern).
    body_size, total_size = 0, 0
    for _ in range(6):
        body, syms = assemble(ORIGIN, body_size, total_size,
                              "size")
        nbs = syms["body_end"] - syms["stub"]
        nts = nbs + (nbs + 7) // 8 + 16
        if nbs == body_size and nts == total_size:
            break
        body_size, total_size = nbs, nts
    else:
        raise SystemExit("size did not converge")
    assert len(body) == body_size, "body length mismatch"
    assert body_size > 256, "body too small (DIRBUF pitfall)"

    # Pass 2: the three ORG builds and the diff.
    bodies, allsyms = {}, {}
    for org in ORGS:
        b, s = assemble(org, body_size, total_size,
                        "org%04x" % org)
        assert len(b) == body_size
        bodies[org], allsyms[org] = b, s

    def diff_marks(a, b, delta):
        marks = set()
        for i in range(body_size):
            if a[i] != b[i]:
                assert (b[i] - a[i]) & 0xFF == delta & 0xFF, \
                    "byte %d: 0x%02x -> 0x%02x is not a page " \
                    "delta" % (i, a[i], b[i])
                marks.add(i)
        return marks

    m1 = diff_marks(bodies[0x4000], bodies[0x4100], +1)
    m2 = diff_marks(bodies[0x4000], bodies[0x4200], +2)
    assert m1 == m2, "mark sets from the two diffs disagree"
    bitmap = bytearray((body_size + 7) // 8)
    for off in m1:
        bitmap[off // 8] |= 1 << (7 - (off % 8))
    bitmap = bytes(bitmap)

    # Pass 3: host relocation proof - simulate the stub
    # patch and compare against fresh assemblies.
    for target in FRESH:
        delta = (target - ORIGIN) // 256
        fb, _ = assemble(target, body_size, total_size,
                         "fresh%04x" % target)
        sim = simulate(bodies[ORIGIN], bitmap, delta)
        assert sim == fb, \
            "relocation mismatch at ORG 0x%04x" % target
        print("host relocation check 0x%04x: OK "
              "(%d marked bytes)" % (target, len(m1)))

    entry_off = allsyms[ORIGIN]["entry"] - ORIGIN
    image = build_image(bodies[ORIGIN], bitmap, ORIGIN,
                        entry_off)
    assert len(image) == total_size
    zero = build_image(bodies[ORIGIN], bytes(len(bitmap)),
                       ORIGIN, entry_off)

    with open(os.path.join(BUILD, "rdbg.tosr"), "wb") as f:
        f.write(image)
    with open(os.path.join(BUILD, "rdbg0.tosr"), "wb") as f:
        f.write(zero)
    with open(os.path.join(BUILD, "rdbg_base.bin"), "wb") as f:
        f.write(bodies[ORIGIN])
    with open(os.path.join(BUILD, "rdbg_base.sym"), "w") as f:
        for name in sorted(allsyms[ORIGIN]):
            f.write("%s EQU %04XH\n" % (name,
                                        allsyms[ORIGIN][name]))

    keys = ["stub", "entry", "prompt", "resume", "s_bp",
            "s_int", "s_retcatch", "cap_body", "stopped",
            "sd_ro_end", "after_core", "saved_sp",
            "sd_ei_slot", "sd_sv", "body_end", "INBUF",
            "LINEBUF"]
    js = {k: allsyms[ORIGIN][k] for k in keys}
    js["origin"] = ORIGIN
    js["body_size"] = body_size
    js["total_size"] = total_size
    js["marks"] = len(m1)
    with open(os.path.join(BUILD, "rdbg-symbols.json"),
              "w") as f:
        json.dump(js, f, indent=1, sort_keys=True)
    print("RDBG body %d bytes, bitmap %d bytes, image %d "
          "bytes, %d relocation marks, entry offset %d"
          % (body_size, len(bitmap), total_size, len(m1),
             entry_off))
    print("build/rdbg.tosr written")


if __name__ == "__main__":
    main()
